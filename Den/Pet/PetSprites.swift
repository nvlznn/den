// Den 的角色都不是真實的動物，而是看不出是什麼的小東西。
//
// 共同的畫法：
// - 1-bit，16×16。輪廓圓、形狀簡單，表情只有兩隻眼睛，沒有嘴，所以永遠是平靜的。
// - 實心的身體上，眼睛是挖空的洞；空心的身體上，眼睛是亮點。
// - 眨眼和睡覺時眼睛變成一條橫線；開心時變成「^ ^」。
// - 看書時角色不動，只有角色和一本攤開的書，不畫手。書是 12×7，只有兩頁、沒有書套：兩頁頂邊在書脊凹下去，
//   底部一條線。眼睛下面留一列身體、再空一列，然後是書，書蓋住下半身，
//   所以看書的影格比 16 列高（17–21 列），其他影格都是 16×16。
// - 外觀不會隨等級改變。每隻角色的等級各自計算。
//
// 六隻角色：
// - 方方 Boxy（預設）：實心的方塊，兩隻短手、兩隻腳，頭上浮著一顆小點。最有「小機器」的感覺。
// - 豆豆 Bean：實心的圓角豆子，兩隻小腳。最單純的一隻。
// - 麻糬 Mochi：空心的扁圓糰子，頭上一片小芽，沒有手腳，最安靜。
// - 水滴 Drop：空心的白色水滴，尖頭朝上，眼睛低低的。
// - 雲雲 Puff：空心的雲朵，頂上兩個鼓包，底下兩隻細腳。
// - 圓仔 Orb：實心的圓球，頭上一根彎彎的天線。
//
// 編輯方式：`#` 是亮的像素，`.` 是沒亮的。寬度都是 16；除了看書，高度也都是 16。

/// 一隻可以選的角色。只有資料，不依賴任何 UI 框架，Live Activity 也會用到。
struct PetCharacter: Identifiable, Hashable, Sendable {
    let id: String
    let name: String
    let idle: [String]
    /// 待機時偶爾眨眼。
    let blink: [String]
    let study1: [String]
    /// 視線移到右頁。
    let study2: [String]
    let sleep: [String]
    let happy: [String]
    var isEgg: Bool { id == "egg" || id.hasPrefix("egg.") }
}

enum EggColor: String, CaseIterable, Codable, Hashable, Sendable, Identifiable {
    case white, black
    var id: String { rawValue }
    var name: String { self == .white ? String(localized: "White Egg") : String(localized: "Black Egg") }
    var spriteID: String { "egg.\(rawValue)" }
    var characterIDs: [String] {
        switch self {
        case .white: ["mochi", "drop", "cloud"]
        case .black: ["fangfang", "doudou", "orb"]
        }
    }
    static func of(characterID: String) -> EggColor? {
        allCases.first { $0.characterIDs.contains(characterID) }
    }
}

