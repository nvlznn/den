// Den 的角色都不是真實的動物，而是看不出是什麼的小東西。
//
// 共同的畫法：
// - 1-bit，16×16。輪廓圓、形狀簡單，表情只有兩隻眼睛，沒有嘴，所以永遠是平靜的。
// - 實心的身體上，眼睛是挖空的洞；空心的身體上，眼睛是亮點。
// - 眨眼和睡覺時眼睛變成一條橫線；開心時變成「^ ^」。
// - 看書時身前有一本攤開的書；實心的角色在書的上方和兩側留一圈暗縫，書才不會和身體黏在一起。
// - 外觀不會隨等級改變。每隻角色的等級各自計算。
//
// 六隻角色：
// - 方方 Boxy（預設）：實心的方塊，兩隻短手、兩隻腳，頭上浮著一顆小點。最有「小機器」的感覺。
// - 豆豆 Bean：實心的圓角豆子，兩隻小腳。最單純的一隻。
// - 麻糬 Mochi：空心的扁圓糰子，頭上一片小芽，沒有手腳，最安靜。
// - 水滴 Drop：實心的水滴，尖頭朝上，眼睛低低的。
// - 雲雲 Puff：空心的雲朵，頂上兩個鼓包，底下兩隻細腳。
// - 圓仔 Orb：實心的圓球，頭上一根彎彎的天線。
//
// 編輯方式：`#` 是亮的像素，`.` 是沒亮的。每格都是 16×16。

/// 一隻可以選的角色。只有資料，不依賴任何 UI 框架，Live Activity 也會用到。
