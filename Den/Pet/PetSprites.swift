// - 開心時眼睛變成「^ ^」，看書時前面多一本攤開的書，睡覺時耳朵塌下來、整隻縮成一團。
// - 外觀不會隨等級改變。
//
// 編輯方式：`#` 是亮的像素，`.` 是沒亮的。每格都是 16×16。

